def _fill_missing_tags() -> None:
    """Generate placeholder samples for tags not yet defined in TAG_SAMPLES."""
    generic_variants = [
        [("Hôm nay muốn món phù hợp", ["mood_normal", "weather_normal"]),
         ("Cần gợi ý món ăn phù hợp", ["pref_convenient"]),
         ("Giúp mình chọn món nhé", ["mood_normal"])],
        [("Mình đang tìm món ăn", ["pref_flavorful"]),
         ("Có món nào hợp không", ["mood_normal"]),
         ("Muốn thử món mới", ["mood_excited"])],
        [("Hôm nay ăn gì cho ngon", ["pref_flavorful"]),
         ("Gợi ý món cho tôi", ["pref_convenient"]),
         ("Thèm đổi vị một chút", ["mood_bored_taste"])],
        [("Cần món ăn phù hợp lúc này", ["weather_normal"]),
         ("Muốn món dễ ăn", ["pref_convenient"]),
         ("Hôm nay không biết ăn gì", ["mood_lazy"])],
    ]
    tag_labels = {
        t["id"]: t["label_vi"]
        for t in json.loads((LAYER1 / "tags.json").read_text(encoding="utf-8"))["system_tags"]
    }
    for tag in TAGS:
        if tag in TAG_SAMPLES:
            continue
        label = tag_labels.get(tag, tag)
        TAG_SAMPLES[tag] = []
        for vi, base in enumerate(generic_variants):
            TAG_SAMPLES[tag].append([
                (f"{base[0][0]} liên quan {label.lower()}", base[0][1]),
                (f"Mình thích kiểu {label.lower()}", ["pref_flavorful", "mood_normal"]),
                (f"Muốn món có đặc điểm {label.lower()}", ["pref_convenient", "mood_normal"]),
            ])


def build_dataset(variant_idx: int) -> list[dict]:
    samples: list[dict] = []
    seen_text: set[str] = set()
    for tag in TAGS:
        variants = TAG_SAMPLES[tag]
        entries = variants[variant_idx % len(variants)]
        for text, extras in entries:
            tags = [tag] + [t for t in extras if t != tag]
            tags = list(dict.fromkeys(tags))
            unique_text = text if text not in seen_text else f"{text} ({tag})"
            seen_text.add(unique_text)
            samples.append({"text": unique_text, "tags": tags})
    return samples


def write_dataset(dataset_id: str, variant_idx: int) -> int:
    out_dir = LAYER1 / dataset_id
    out_dir.mkdir(parents=True, exist_ok=True)
    samples = build_dataset(variant_idx)

    json_path = out_dir / "intent_train_data.json"
    json_path.write_text(json.dumps(samples, ensure_ascii=False, indent=2), encoding="utf-8")

    csv_path = out_dir / "intent_samples.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(["text", "tags"])
        for row in samples:
            writer.writerow([row["text"], "|".join(row["tags"])])

    return len(samples)


def validate(samples: list[dict]) -> None:
    counts = {tag: 0 for tag in TAGS}
    for row in samples:
        for tag in row["tags"]:
            if tag in counts:
                counts[tag] += 1
    missing = [t for t, c in counts.items() if c < 3]
    if missing:
        raise ValueError(f"Tags with <3 occurrences: {missing}")
    if len(samples) < 100:
        raise ValueError(f"Only {len(samples)} samples, need >=100")


def main() -> None:
    _fill_missing_tags()
    new_ids = ["dataset_v002", "dataset_v003", "dataset_v004", "dataset_v005"]
    for idx, dataset_id in enumerate(new_ids):
        samples = build_dataset(idx)
        validate(samples)
        count = write_dataset(dataset_id, idx)
        print(f"{dataset_id}: {count} samples, min tag count OK")

    meta_path = LAYER1 / "datasets.json"
    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    available = list(meta.get("available_datasets", ["dataset_v001"]))
    for dataset_id in new_ids:
        if dataset_id not in available:
            available.append(dataset_id)
    meta["available_datasets"] = available
    meta["max_dataset_size"] = max(meta.get("max_dataset_size", 100), 160)
    meta_path.write_text(json.dumps(meta, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("Updated datasets.json")


if __name__ == "__main__":
    main()
